from __future__ import annotations

from sqlalchemy import inspect
from sqlalchemy import text
from sqlalchemy.engine import Connection


def _table_exists(connection: Connection, table_name: str) -> bool:
    inspector = inspect(connection)
    return table_name in inspector.get_table_names()


def apply(connection: Connection) -> None:
    if _table_exists(connection, "user_calendar_events"):
        return

    date_type = "DATE"
    if connection.dialect.name == "postgresql":
        id_definition = "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    else:
        id_definition = "INTEGER PRIMARY KEY"

    connection.execute(
        text(
            f"""
            CREATE TABLE user_calendar_events (
                id {id_definition},
                event_type VARCHAR NOT NULL,
                start_date {date_type} NOT NULL,
                end_date {date_type} NOT NULL,
                description VARCHAR
            )
            """
        )
    )
    connection.execute(text("CREATE INDEX IF NOT EXISTS ix_user_calendar_events_event_type ON user_calendar_events (event_type)"))
    connection.execute(text("CREATE INDEX IF NOT EXISTS ix_user_calendar_events_start_date ON user_calendar_events (start_date)"))
    connection.execute(text("CREATE INDEX IF NOT EXISTS ix_user_calendar_events_end_date ON user_calendar_events (end_date)"))
