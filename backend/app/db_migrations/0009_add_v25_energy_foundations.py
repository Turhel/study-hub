from __future__ import annotations

from sqlalchemy import inspect
from sqlalchemy import text
from sqlalchemy.engine import Connection


def _table_exists(connection: Connection, table_name: str) -> bool:
    inspector = inspect(connection)
    return table_name in inspector.get_table_names()


def _column_exists(connection: Connection, table_name: str, column_name: str) -> bool:
    inspector = inspect(connection)
    columns = inspector.get_columns(table_name)
    return any(str(column.get("name")) == column_name for column in columns)


def _add_block_mastery_column_if_missing(connection: Connection, column_name: str, definition: str) -> None:
    if not _table_exists(connection, "block_mastery"):
        return
    if _column_exists(connection, "block_mastery", column_name):
        return
    connection.execute(text(f"ALTER TABLE block_mastery ADD COLUMN {column_name} {definition}"))


def _create_user_energy_settings_if_missing(connection: Connection) -> None:
    if _table_exists(connection, "user_energy_settings"):
        return

    if connection.dialect.name == "postgresql":
        connection.execute(
            text(
                """
                CREATE TABLE user_energy_settings (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id INTEGER NOT NULL DEFAULT 1,
                    mode_dia_leve BOOLEAN NOT NULL DEFAULT FALSE,
                    mode_provas_academicas BOOLEAN NOT NULL DEFAULT FALSE,
                    provas_activated_at TIMESTAMP,
                    current_daily_target_questions INTEGER NOT NULL DEFAULT 20
                )
                """
            )
        )
    else:
        connection.execute(
            text(
                """
                CREATE TABLE user_energy_settings (
                    id INTEGER PRIMARY KEY,
                    user_id INTEGER NOT NULL DEFAULT 1,
                    mode_dia_leve BOOLEAN NOT NULL DEFAULT 0,
                    mode_provas_academicas BOOLEAN NOT NULL DEFAULT 0,
                    provas_activated_at DATETIME,
                    current_daily_target_questions INTEGER NOT NULL DEFAULT 20
                )
                """
            )
        )


def _ensure_default_energy_row(connection: Connection) -> None:
    row = connection.execute(text("SELECT id FROM user_energy_settings LIMIT 1")).first()
    if row is not None:
        return
    connection.execute(
        text(
            """
            INSERT INTO user_energy_settings (
                user_id,
                mode_dia_leve,
                mode_provas_academicas,
                current_daily_target_questions
            )
            VALUES (:user_id, :mode_dia_leve, :mode_provas_academicas, :target_questions)
            """
        ),
        {
            "user_id": 1,
            "mode_dia_leve": False,
            "mode_provas_academicas": False,
            "target_questions": 20,
        },
    )


def apply(connection: Connection) -> None:
    _add_block_mastery_column_if_missing(connection, "eaere_stage", "VARCHAR DEFAULT 'E1'")
    _add_block_mastery_column_if_missing(connection, "ex_moving_average", "FLOAT")
    _add_block_mastery_column_if_missing(connection, "consecutive_failures", "INTEGER DEFAULT 0")
    connection.execute(text("CREATE INDEX IF NOT EXISTS ix_block_mastery_eaere_stage ON block_mastery (eaere_stage)"))

    _create_user_energy_settings_if_missing(connection)
    connection.execute(text("CREATE INDEX IF NOT EXISTS ix_user_energy_settings_user_id ON user_energy_settings (user_id)"))
    _ensure_default_energy_row(connection)
